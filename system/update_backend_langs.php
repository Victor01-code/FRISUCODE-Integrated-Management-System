$langs = ['en', 'sw', 'fr', 'de'];

foreach ($langs as $lang) {
    $file = __DIR__ . "/../system/lang/{$lang}.php";
    if (file_exists($file)) {
        $content = file_get_contents($file);
        $newKeysStr = "\n    // ========================= NEW GENERATED KEYS =========================\n";
        foreach ($keysToAdd as $masterKey => $translations) {
            $trans = str_replace("'", "\\'", $translations[$lang]);
            $newKeysStr .= "    '$masterKey' => '$trans',\n";
        }
        
        $content = str_replace("];\n", $newKeysStr . "];\n", $content);
        $content = str_replace("];\r\n", $newKeysStr . "];\r\n", $content);
        
        file_put_contents($file, $content);
        echo "Updated $lang.php\n";
    }
}
echo "Done.";
